class Command(BaseCommand):
    help = "Seed the Akashic Store with rich demo books across all 11 canonical genres with multi-store ownership."

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Simulate the seeding process without committing database changes.",
        )
        parser.add_argument(
            "--update-styling-only",
            action="store_true",
            help="Update card_customization and BDP hero_theme across existing StoreProducts for optimal pastel contrast without modifying products, prices, inventories, or orders.",
        )

    def handle(self, *args, **options):
        dry_run = options["dry_run"]
        update_styling_only = options.get("update_styling_only", False)

        if update_styling_only:
            self.stdout.write(self.style.MIGRATE_HEADING("=== UPDATING STOREFRONT PALETTE & CONTRAST (80% PASTEL, 20% ACCENT) ==="))
            products = list(StoreProduct.objects.all().order_by("created_at", "id"))
            self.stdout.write(f"Found {len(products)} StoreProducts to update.")
            updated_count = 0
            for idx, prod in enumerate(products):
                palette = get_curated_palette(idx)
                genres = list(prod.custom_genres) if prod.custom_genres else []
                prod.card_customization = {
                    "background_color": palette["bg"],
                    "title_color": palette["title_color"],
                    "description_color": palette["desc_color"],
                    "genre_badge_colors": {
                        g: "#000000" if g == "Horror" else ("#00e500" if "Sci" in g else "#9e81e4")
                        for g in genres
                    },
                }
                if not dry_run:
                    prod.save(update_fields=["card_customization"])

                detail, _ = StoreProductDetail.objects.get_or_create(product=prod)
                hero = dict(detail.hero_theme) if detail.hero_theme else {}
                hero["background_color"] = palette["bg"]
                hero["wave_color"] = palette["wave"]
                hero["title_color"] = palette["title_color"]
                detail.hero_theme = hero
                if not dry_run:
                    detail.save(update_fields=["hero_theme"])

                updated_count += 1

            self.stdout.write(self.style.SUCCESS(f"✨ Successfully refreshed {updated_count} StoreProducts with WCAG AA pastel/accent palette! ✨"))
            return

        self.stdout.write(self.style.MIGRATE_HEADING("=== SEEDING MULTI-STORE DEMO CATALOGUE ==="))

        # 1. Ensure Demo Store Managers exist
        managers = []
        for m_info in DEMO_MANAGERS:
            mgr = User.objects.filter(username=m_info["username"]).first()
            if not mgr:
                if not dry_run:
                    mgr = User.objects.create_user(
                        username=m_info["username"],
                        email=m_info["email"],
                        password="Manager123!@#",
                        role=UserRole.STORE_MANAGER,
                        manager_status=ManagerStatus.APPROVED,
                        business_name=m_info["business_name"],
                        display_name=m_info["display_name"],
                        is_active=True,
                    )
                    self.stdout.write(self.style.SUCCESS(f"  + Created manager: {mgr.username} ({m_info['business_name']})"))
                else:
                    self.stdout.write(f"  [Dry-run] Would create manager: {m_info['username']}")
                    continue
            else:
                if not dry_run:
                    # Update fields to ensure approved status and proper store business name
                    mgr.role = UserRole.STORE_MANAGER
                    mgr.manager_status = ManagerStatus.APPROVED
                    mgr.business_name = m_info["business_name"]
                    mgr.display_name = m_info["display_name"]
                    mgr.is_active = True
                    mgr.set_password("Manager123!@#")
                    mgr.save()
                    self.stdout.write(f"  ✓ Verified manager: {mgr.username} ({mgr.business_name})")
            if mgr:
                managers.append(mgr)

        if dry_run and not managers:
            managers = [User(username=m["username"], business_name=m["business_name"]) for m in DEMO_MANAGERS]

        # 2. Iterate through catalogue definitions
        created_products = 0
        updated_products = 0
        genre_counts = {g: 0 for g in CANONICAL_GENRES}
        manager_counts = {m.username: 0 for m in managers}

        col = _get_collection()

        for idx, book_def in enumerate(CATALOGUE_DEFINITIONS):
            title = book_def["title"]
            isbn13 = book_def["isbn13"]
            genres = book_def["genres"]

            # Upsert into MongoDB
            if not dry_run:
                normalized = NormalizedBook(
                    title=title,
                    authors=book_def["authors"],
                    description=book_def["description"],
                    isbn13=isbn13,
                    subjects=genres,
                    cover_urls=[book_def["cover_url"]],
                    source_name="akashic_curated_seed",
                    source_id=isbn13,
                )
                book_ref = upsert_book(normalized)
            else:
                book_ref = f"dry_run_{isbn13}"

            # Primary manager for this book (round-robin)
            primary_mgr = managers[idx % len(managers)]

            # Store offers to create (1 primary, plus 1 or 2 alt offers if flagship)
            offers_to_create = [
                {
                    "manager": primary_mgr,
                    "price": book_def["price"],
                    "edition": book_def["edition"],
                    "stock": book_def["stock"],
                }
            ]

            if book_def.get("flagship_multi_store"):
                # Add 2nd offer from another manager
                alt_mgr = managers[(idx + 1) % len(managers)]
                offers_to_create.append(
                    {
                        "manager": alt_mgr,
                        "price": book_def.get("alt_price", book_def["price"] + Decimal("2.00")),
                        "edition": f"{alt_mgr.business_name} Exclusive Archival",
                        "stock": max(15, book_def["stock"] - 10),
                    }
                )
                # If popular classic, add 3rd offer
                if idx % 3 == 0 and len(managers) >= 3:
                    third_mgr = managers[(idx + 2) % len(managers)]
                    offers_to_create.append(
                        {
                            "manager": third_mgr,
                            "price": book_def["price"] + Decimal("4.00"),
                            "edition": f"{third_mgr.business_name} Leatherbound Limited",
                            "stock": 20,
                        }
                    )

            for offer in offers_to_create:
                mgr = offer["manager"]
                if dry_run:
                    created_products += 1
                    manager_counts[mgr.username] = manager_counts.get(mgr.username, 0) + 1
                    for g in genres:
                        for cg in CANONICAL_GENRES:
                            if cg.lower() in g.lower() or g.lower() in cg.lower():
                                genre_counts[cg] += 1
                    continue

                prod, created = StoreProduct.objects.get_or_create(
                    book_reference=book_ref,
                    created_by=mgr,
                    defaults={
                        "price": offer["price"],
                        "edition": offer["edition"],
                        "condition": "New",
                        "status": StoreStatus.IN_STOCK,
                        "custom_cover_url": book_def["cover_url"],
                        "custom_description": book_def["description"],
                        "custom_genres": genres,
                        "card_customization": {
                            "background_color": book_def.get("bg_color", "#1c1917"),
                            "title_color": book_def.get("title_color", "#ffffff"),
                            "description_color": "#d1d5db",
                            "genre_badge_colors": {
                                g: "#000000" if g == "Horror" else ("#00e500" if "Sci" in g else "#9e81e4")
                                for g in genres
                            },
                        },
                    },
                )

                # Ensure stock is updated
                inv, _ = Inventory.objects.get_or_create(product=prod)
                inv.quantity = offer["stock"]
                inv.reserved_quantity = 0
                inv.save()

                prod.status = StoreStatus.IN_STOCK
                prod.price = offer["price"]
                prod.edition = offer["edition"]
                prod.custom_cover_url = book_def["cover_url"]
                prod.custom_description = book_def["description"]
                prod.custom_genres = genres
                cur_pal = get_curated_palette(created_products + updated_products)
                prod.card_customization = {
                    "background_color": cur_pal["bg"],
                    "title_color": cur_pal["title_color"],
                    "description_color": cur_pal["desc_color"],
                    "genre_badge_colors": {
                        g: "#000000" if g == "Horror" else ("#00e500" if "Sci" in g else "#9e81e4")
                        for g in genres
                    },
                }
                prod.save()

                # Ensure BDP detail record
                orig_p = offer["price"] + Decimal("5.00")
                StoreProductDetail.objects.update_or_create(
                    product=prod,
                    defaults={
                        "original_price": orig_p,
                        "synopsis": book_def["description"],
                        "full_description": f"{book_def['description']}\n\nSupplied exclusively through {mgr.business_name} for the Akashic Library Curated Store. Carefully inspected and archived for bibliophiles.",
                        "why_we_chose": f"Selected by {mgr.business_name} for its exceptional craft, distinctive literary voice, and timeless aesthetic resonance in {genres[0] if genres else 'fiction'}.",
                        "excerpt": f"\"It was a moment that divided before from after, etched into memory like letters carved in stone...\" — from {title}",
                        "hero_theme": {
                            "background_color": cur_pal["bg"],
                            "wave_color": cur_pal["wave"],
                            "title_color": cur_pal["title_color"],
                            "accent_color": "#ff008f",
                        },
                        "at_a_glance": [
                            {"icon": "🪄", "label": g, "bg_color": "", "text_color": ""}
                            for g in genres[:4]
                        ],
                        "editorial_cards": [
                            {
                                "heading": "Curator's Note",
                                "quote": f"A triumph of modern storytelling. {title} delivers unforgettable depth and exquisite emotional pacing.",
                                "attribution": f"— Senior Curator, {mgr.business_name}",
                                "bg_color": "#fef08a",
                                "text_color": "#171717",
                            },
                            {
                                "heading": "Critical Praise",
                                "quote": "Utterly singular and impossible to put down. An essential addition to any curated library.",
                                "attribution": "— The Literary Chronicle",
                                "bg_color": "#fbcfe8",
                                "text_color": "#171717",
                            },
                        ],
                        "content_warnings": [],
                    },
                )

                if created:
                    created_products += 1
                else:
                    updated_products += 1

                manager_counts[mgr.username] = manager_counts.get(mgr.username, 0) + 1
                for g in genres:
                    for cg in CANONICAL_GENRES:
                        if cg.lower() in g.lower() or g.lower() in cg.lower():
                            genre_counts[cg] += 1

        # 3. Print Comprehensive Report
        self.stdout.write(self.style.SUCCESS("\n=== CATALOGUE SEEDING REPORT ==="))
        self.stdout.write(f"Total Unique Titles Curated: {len(CATALOGUE_DEFINITIONS)}")
        self.stdout.write(f"Total Store Products Seeded: {created_products + updated_products}")
        self.stdout.write(f"  - Newly Created: {created_products}")
        self.stdout.write(f"  - Verified/Updated: {updated_products}")
        self.stdout.write("\nDistribution Across Approved Store Managers:")
        for u, count in manager_counts.items():
            b_name = next((m.business_name for m in managers if m.username == u), "")
            self.stdout.write(f"  • {u} ({b_name}): {count} products")

        self.stdout.write("\nDistinct Book Entries Per Authoritative Genre:")
        all_met = True
        for g, count in sorted(genre_counts.items()):
            met = "✓" if count >= 20 else "⚠️"
            if count < 20:
                all_met = False
            self.stdout.write(f"  {met} {g.ljust(22)}: {count} books")

        if all_met:
            self.stdout.write(self.style.SUCCESS("\n✨ ALL 11 GENRES MET TARGET (>= 20-25 distinct entries)! ✨"))
        else:
            self.stdout.write(self.style.WARNING("\nSome genres below 20 entries target."))

        self.stdout.write("================================================\n")
