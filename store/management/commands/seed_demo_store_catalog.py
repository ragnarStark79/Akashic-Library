def get_wcag_contrast_colors(hex_color: str):
    hex_color = (hex_color or "").lstrip("#")
    if len(hex_color) == 3:
        hex_color = "".join([c * 2 for c in hex_color])
    try:
        r, g, b = [int(hex_color[i:i+2], 16) / 255.0 for i in (0, 2, 4)]
    except Exception:
        return "#111827", "#4B5563"

    def chan(c):
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    lum = 0.2126 * chan(r) + 0.7152 * chan(g) + 0.0722 * chan(b)
    if lum > 0.38:
        return "#111827", "#4B5563"
    else:
        return "#FFFFFF", "#D1D5DB"

def get_curated_palette(index: int):
    # 80% pastel, 20% dark accent (every 5th is accent)
    if index % 5 == 4:
        item = ACCENT_PALETTE[(index // 5) % len(ACCENT_PALETTE)]
    else:
        pastel_idx = (index - (index // 5)) % len(PASTEL_PALETTE)
        item = PASTEL_PALETTE[pastel_idx]

    title_col, desc_col = get_wcag_contrast_colors(item["bg"])
    return {
        "bg": item["bg"],
        "wave": item["wave"],
        "title_color": title_col,
        "desc_color": desc_col,
    }

